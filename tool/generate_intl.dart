// ignore_for_file: avoid_print

/// Generates typed localization classes from the JSON string sources.
///
/// Source of truth: `lib/intl/json/intl_<locale>.json`
///
/// Outputs:
/// - `lib/intl/app_strings.g.dart`          (abstract `AppStrings`)
/// - `lib/intl/app_strings_<locale>.g.dart` (per-locale values)
library;

import 'dart:async';
import 'dart:convert';
import 'dart:io';

import 'package:built_collection/built_collection.dart';
import 'package:code_builder/code_builder.dart';
import 'package:dart_style/dart_style.dart' show DartFormatter;
import 'package:rxdart/rxdart.dart';

final String intlPath = '${Directory.current.path}/lib/intl';
final String jsonPath = '$intlPath/json';
bool _isGenerating = false;

class LocaleGenerator {
  LocaleGenerator(this.json);

  final Map<String, String>? json;
  final DartEmitter emitter = DartEmitter();
  final DartFormatter formatter =
      DartFormatter(languageVersion: DartFormatter.latestLanguageVersion);

  Future<void> buildAndGenerateLocaleClass({
    bool abstract = true,
    String suffix = '',
  }) async {
    final ListBuilder<Method> methodBuilder = ListBuilder<Method>(<Method>[]);
    json!.forEach((String k, String v) {
      methodBuilder.add(
        _buildMethodFor(
          k,
          v,
          abstract: abstract,
        ),
      );
    });
    final Class intlLocaleClass = Class((ClassBuilder b) {
      b
        ..name = 'AppStrings${suffix.toUpperCase()}'
        ..methods = methodBuilder
        ..abstract = abstract
        ..extend = abstract ? null : refer('AppStrings')
        ..constructors = ListBuilder<Constructor>(<Constructor>[]);
    });
    final StringBuffer buffer = StringBuffer(_generatedHeader(suffix));
    if (!abstract) {
      buffer
        ..writeln()
        ..writeln("import 'app_strings.g.dart';");
    }
    buffer
      ..writeln()
      ..write(intlLocaleClass.accept(emitter));
    File('$intlPath/app_strings${(suffix.isNotEmpty) ? '_$suffix' : ''}.g.dart')
        .writeAsStringSync(formatter.format(buffer.toString()));
  }

  Method _buildMethodFor(
    String key,
    String value, {
    bool abstract = false,
  }) {
    final List<String> args = <String>[];
    final List<String> argNames = <String>[];
    final RegExp regExp = RegExp(r'({\w+})');
    String strippedValue = jsonEncode(value);
    if (strippedValue.contains(r'$')) {
      strippedValue = strippedValue.replaceAll(r'$', r'\$');
    }
    if (regExp.hasMatch(strippedValue)) {
      for (final Match m in regExp.allMatches(strippedValue).toList()) {
        final String arg = m.group(0)!;
        args.add(arg);
        argNames.add(arg.substring(1, arg.length - 1));
      }
      for (final String a in args) {
        strippedValue =
            strippedValue.replaceAll(a, '\$${a.substring(1, a.length - 1)}');
      }
    }

    String code = '';
    if (!abstract) {
      code = 'return $strippedValue;';
    }

    final Method method = Method((MethodBuilder b) {
      b
        ..name = key
        ..type = argNames.isEmpty ? MethodType.getter : null
        ..returns = refer('String')
        ..requiredParameters = ListBuilder<Parameter>(
          argNames.map((String s) {
            return Parameter((ParameterBuilder b) {
              b
                ..name = s
                ..type = refer('dynamic');
            });
          }).toList(),
        );
      if (!abstract) {
        b
          ..body = Code(code)
          ..annotations = ListBuilder<Expression>(<Expression>[
            const CodeExpression(Code('override')),
          ]);
      }
    });

    return method;
  }
}

String _generatedHeader(String suffix) {
  final String source = suffix.isEmpty
      ? 'intl_en.json (key set)'
      : 'json/intl_$suffix.json';
  return '// GENERATED CODE - DO NOT MODIFY BY HAND.\n'
      '// Generated by tool/generate_intl.dart from $source.\n'
      '// ignore_for_file: type=lint\n';
}

Map<String, String> _getJsonLocaleFor(String locale) {
  return (jsonDecode(File('$jsonPath/intl_$locale.json').readAsStringSync())
          as Map<dynamic, dynamic>)
      .cast<String, String>();
}

Future<void> _generateIntlFromJson() async {
  print('\nGenerating locale classes...');
  final Map<String, String> englishJson = _getJsonLocaleFor('en');
  await LocaleGenerator(englishJson).buildAndGenerateLocaleClass();
  final List<FileSystemEntity> list = Directory(jsonPath).listSync();
  for (final FileSystemEntity entity in list) {
    final String fileName = entity.path.split('/').last;
    if (!fileName.startsWith('intl_') || !fileName.endsWith('.json')) {
      continue;
    }
    final String locale = fileName.split('_').last.split('.').first;
    print('Generating locale classes for $locale...');
    final Map<String, String> json = _getJsonLocaleFor(locale);
    _warnAboutMissingKeys(locale, json.keys.toSet(), englishJson.keys);
    for (final String key in englishJson.keys) {
      json[key] ??= englishJson[key]!;
    }
    await LocaleGenerator(json).buildAndGenerateLocaleClass(
      abstract: false,
      suffix: locale,
    );
  }
  print('Success!\n');
}

void _warnAboutMissingKeys(
  String locale,
  Set<String> providedKeys,
  Iterable<String> englishKeys,
) {
  final List<String> missing =
      englishKeys.where((String key) => !providedKeys.contains(key)).toList();
  if (missing.isEmpty) {
    return;
  }
  stderr.writeln(
    'Warning: intl_$locale.json is missing ${missing.length} key(s) present '
    'in intl_en.json (English fallback used): ${missing.join(', ')}',
  );
}

Future<void> _onFileSaved(FileSystemEvent? event) async {
  if (_isGenerating) {
    return;
  }
  _isGenerating = true;
  try {
    await _generateIntlFromJson();
  } catch (e) {
    print(e);
  }
  _isGenerating = false;
}

Future<void> main(List<String>? args) async {
  args ??= <String>[];
  late StreamSubscription<FileSystemEvent> subscription;
  if (args.contains('--watch')) {
    print('Watching...');
    final Directory directory = Directory(jsonPath);
    subscription =
        directory.watch(events: FileSystemEvent.modify).debounce((_) {
      return TimerStream<bool>(true, const Duration(milliseconds: 600));
    }).listen(_onFileSaved)
          ..onError((Object e, StackTrace s) {
            print('Unhandled Error: $e');
            subscription.cancel();
          });
  }
  await _onFileSaved(null);
}
